const getTranslation = (language, key) => translations[language]?.[key] || translations.en[key] || key;
window.sumateraTranslate = key => getTranslation(document.documentElement.lang, key);

const setTheme = theme => {
    const selectedTheme = theme === 'light' ? 'light' : 'dark';
    document.documentElement.dataset.theme = selectedTheme;
    try {
        localStorage.setItem('sumateramall-theme', selectedTheme);
    } catch (error) {
        console.warn('SumatraMall could not save the selected theme.', error);
    }
    document.querySelectorAll('[data-theme-choice]').forEach(button => {
        const selected = button.dataset.themeChoice === selectedTheme;
        button.setAttribute('aria-pressed', String(selected));
        button.classList.toggle('is-active', selected);
    });
};

try {
    setTheme(localStorage.getItem('sumateramall-theme') || document.documentElement.dataset.theme);
} catch (error) {
    setTheme(document.documentElement.dataset.theme);
}
document.querySelectorAll('[data-theme-choice]').forEach(button => {
    button.addEventListener('click', () => setTheme(button.dataset.themeChoice));
});

const languageSelect = document.getElementById('site-language');
const setTranslatedText = (element, text) => {
    const textNode = Array.from(element.childNodes).find(node =>
        node.nodeType === Node.TEXT_NODE && node.textContent.trim() !== ''
    );
    if (textNode && element.children.length > 0) {
        textNode.textContent = text;
    } else {
        element.textContent = text;
    }
};
const renderLocalizedStatus = element => {
    const key = element.dataset.i18nStatus;
    if (!key) return;
    const parameters = JSON.parse(element.dataset.i18nStatusParams || '{}');
    let text = getTranslation(document.documentElement.lang, key);
    Object.entries(parameters).forEach(([name, value]) => {
        text = text.replace(`:${name}`, String(value));
    });
    element.textContent = text;
};
window.sumateraSetStatus = (element, key, parameters = {}) => {
    if (!element) return;
    element.dataset.i18nStatus = key;
    element.dataset.i18nStatusParams = JSON.stringify(parameters);
    renderLocalizedStatus(element);
};
const setLanguage = language => {
    const selectedLanguage = translations[language] ? language : 'id';
    document.documentElement.lang = selectedLanguage;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const translated = translations[selectedLanguage]?.[element.dataset.i18n] || translations.en[element.dataset.i18n];
        if (translated) setTranslatedText(element, translated);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const translated = translations[selectedLanguage]?.[element.dataset.i18nPlaceholder] || translations.en[element.dataset.i18nPlaceholder];
        if (translated) element.placeholder = translated;
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach(element => {
        const translated = getTranslation(selectedLanguage, element.dataset.i18nAriaLabel);
        if (translated !== element.dataset.i18nAriaLabel) element.setAttribute('aria-label', translated);
    });
    document.querySelectorAll('[data-planner-locale]').forEach(element => {
        element.value = selectedLanguage === 'id' ? 'id' : 'en';
    });
    const voiceLabel = getTranslation(selectedLanguage, 'voice_search_by');
    document.querySelectorAll('[data-voice-search]').forEach(button => {
        button.setAttribute('aria-label', voiceLabel);
        button.title = voiceLabel;
    });
    document.querySelectorAll('[data-theme-choice]').forEach(button => {
        const label = getTranslation(selectedLanguage, button.dataset.themeChoice === 'light' ? 'theme_light' : 'theme_dark');
        button.setAttribute('aria-label', label);
        button.title = label;
    });
    document.querySelector('[data-filter-dock-close]')?.setAttribute('aria-label', getTranslation(selectedLanguage, 'filter_dock_close'));
    document.querySelector('[data-filter-dock-close]')?.setAttribute('title', getTranslation(selectedLanguage, 'filter_dock_close'));
    languageSelect?.setAttribute('aria-label', getTranslation(selectedLanguage, 'language_label'));
    if (languageSelect) languageSelect.value = selectedLanguage;
    document.querySelectorAll('[data-i18n-status]').forEach(renderLocalizedStatus);
    try {
        localStorage.setItem('sumateramall-language', selectedLanguage);
    } catch (error) {
        console.warn('SumatraMall could not save the selected language.', error);
    }
};

let savedLanguage = 'id';
try {
    savedLanguage = localStorage.getItem('sumateramall-language') || 'id';
} catch (error) {
    console.warn('SumatraMall could not read the saved language.', error);
}
setLanguage(savedLanguage);
languageSelect?.addEventListener('change', event => setLanguage(event.target.value));
window.sumateraSetLanguage = setLanguage;

document.querySelectorAll('[data-voice-search]').forEach(button => {
    const input = document.getElementById(button.dataset.voiceInput);
    const status = document.querySelector(`[data-voice-status-for="${button.dataset.voiceInput}"]`);
    const SpeechRecognition = window.SpeechRecognition || window.webkitSpeechRecognition;
    if (!input || !input.form || !status) {
        button.disabled = true;
        return;
    }

    if (!SpeechRecognition) {
        button.disabled = true;
        window.sumateraSetStatus(status, 'voice_unsupported');
        return;
    }

    button.addEventListener('click', () => {
        const recognition = new SpeechRecognition();
        const languages = { id: 'id-ID', en: 'en-US', es: 'es-ES', fr: 'fr-FR', zh: 'zh-CN', ja: 'ja-JP' };
        recognition.lang = languages[document.documentElement.lang] || 'en-US';
        recognition.interimResults = false;
        recognition.maxAlternatives = 1;
        window.sumateraSetStatus(status, 'voice_listening');
        recognition.addEventListener('result', event => {
            input.value = event.results[0][0].transcript;
            window.sumateraSetStatus(status, 'voice_recognized', { query: input.value });
            input.form.requestSubmit();
        });
        recognition.addEventListener('error', () => {
            window.sumateraSetStatus(status, 'voice_failed');
        });
        recognition.addEventListener('end', () => {
            if (status.dataset.i18nStatus === 'voice_listening') {
                status.removeAttribute('data-i18n-status');
                status.removeAttribute('data-i18n-status-params');
                status.textContent = '';
            }
        });
        try {
            recognition.start();
        } catch (error) {
            console.warn('SumatraMall voice search could not start.', error);
            window.sumateraSetStatus(status, 'voice_failed');
        }
    });
});
